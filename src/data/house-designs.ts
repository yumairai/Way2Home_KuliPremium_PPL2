export const houseDesigns: HouseDesign[] = designs.map(
  (
    [
      name,
      style,
      location,
      landArea,
      buildingArea,
      bedrooms,
      floors,
      estimatedCost,
      estimatedDuration,
      description,
      highlights,
    ],
    index,
  ) => ({
    slug: `${name.toLowerCase()}-${index + 1}`,
    name,
    style,
    location,
    landArea,
    buildingArea,
    bedrooms,
    floors,
    estimatedCost,
    estimatedDuration,
    description,
    highlights,
    image,
  }),
);

export function getHouseDesign(slug: string) {
  return houseDesigns.find((design) => design.slug === slug);
}
